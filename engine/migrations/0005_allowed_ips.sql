-- Пустой список — вход с любого адреса сети; HTTPS и вход по паролю
-- действуют всегда, список — дополнительная мера. Адрес этого компьютера
-- (127.0.0.1, ::1) разрешён всегда, чтобы администратор не закрыл себе доступ.

CREATE TABLE allowed_ips (
    id         TEXT PRIMARY KEY,
    network    TEXT NOT NULL UNIQUE,  -- сеть в каноническом виде: 10.0.5.0/24, 10.0.5.7/32
    note       TEXT,
    created_at TEXT NOT NULL
) STRICT;
