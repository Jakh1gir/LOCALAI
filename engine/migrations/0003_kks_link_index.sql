-- Уникальность связи задаёт первичный ключ «запись, поле, позиция»: на одной
-- позиции поля один объект. Прежний уникальный индекс не учитывал поле и
-- запрещал, например, один и тот же код в полях «ККС» и «Второй ККС».
-- Индекс по объекту остаётся для поиска записей, связанных с ним.

DROP INDEX ux_links_kks;
CREATE INDEX ix_links_kks ON record_kks_links (kks_id, role, record_seq);
